import {test,expect} from '@playwright/test';
test('misi lengkap, validasi, pergantian film dan jadwal',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  const next=page.getByRole('button',{name:'Lanjut'});
  await expect(next).toBeDisabled();
  await page.getByRole('button',{name:'Pilih film Orbit Terakhir'}).click();
  await page.getByRole('button',{name:'JUM 16'}).click();
  await page.getByRole('button',{name:'16.15',exact:true}).click();
  const occupied=page.locator('.seat.occupied').first();
  await expect(occupied).toBeDisabled();
  await occupied.dispatchEvent('click');
  await expect(page.locator('.seat.selected')).toHaveCount(0);
  await page.getByRole('button',{name:'Kursi B3',exact:true}).click();
  await expect(next).toBeDisabled();
  await page.getByRole('button',{name:'Kursi B4',exact:true}).click();
  await expect(page.locator('.total')).toContainText('93.000');
  await page.locator('.seat:not(.selected):not([disabled])').first().click();
  await expect(page.locator('.seat.selected')).toHaveCount(2);
  await expect(page.getByRole('status')).toContainText('Maksimal 2 kursi');
  await next.click();
  await expect(page.getByRole('dialog')).toContainText('Tidak ada pembayaran atau transaksi nyata');
  await page.getByRole('button',{name:'Kembali ke pesanan'}).click();
  await page.getByRole('button',{name:'Kursi B4',exact:true}).click();
  await expect(next).toBeDisabled();
  await page.getByRole('button',{name:'SAB 17'}).click();
  await expect(page.locator('.seat.selected')).toHaveCount(0);
  await expect(page.locator('.summary')).toContainText('Sabtu, 17 Oktober 2026');
  await page.getByRole('button',{name:'Pilih film Jalan Pulang'}).click();
  await expect(page.locator('.summary h3')).toHaveText('Jalan Pulang');
  await expect(page.getByRole('button',{name:'12.30',exact:true})).toBeVisible();
  await expect(next).toBeDisabled();
  await page.getByRole('button',{name:'12.30',exact:true}).click();
  await page.getByRole('button',{name:'Kursi B3',exact:true}).click();
  await page.getByRole('button',{name:'Kursi B4',exact:true}).click();
  await expect(page.locator('.total')).toContainText('83.000');
  await page.getByRole('button',{name:'15.00',exact:true}).click();
  await expect(page.locator('.seat.selected')).toHaveCount(0);
  await page.getByRole('button',{name:'Pilih film Selepas Senja'}).click();
  await page.getByRole('button',{name:'MIN 18'}).click();
  await page.getByRole('button',{name:'20.00',exact:true}).click();
  await page.getByRole('button',{name:'Kursi B3',exact:true}).click();
  await page.getByRole('button',{name:'Kursi B4',exact:true}).click();
  await expect(page.locator('.total')).toContainText('103.000');
  await expect(next).toBeEnabled();
  expect(errors).toEqual([]);
});
test('observasi muat 1366 × 768, tanpa jawaban dan aset luar',async({page})=>{
  const external=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:5173')&&!r.url().startsWith('data:')) external.push(r.url());});
  await page.goto('/?mode=observasi');
  await expect(page.locator('.seat.selected')).toHaveCount(2);
  await expect(page.locator('.summary')).toContainText('B3, B4');
  await expect(page.locator('.total')).toContainText('93.000');
  await expect(page.getByRole('button',{name:'Lanjut'})).toBeEnabled();
  const size=await page.evaluate(()=>({h:document.documentElement.scrollHeight,w:document.documentElement.scrollWidth}));
  expect(size.h).toBeLessThanOrEqual(768);expect(size.w).toBeLessThanOrEqual(1366);
  await expect(page.locator('body')).not.toContainText(/masalah UI\/UX|kemungkinan perbaikan|CATATAN_GURU|jawaban analisis/i);
  expect(external).toEqual([]);
  await page.screenshot({path:'artifacts/layarkita-observasi.png',fullPage:true});
});
